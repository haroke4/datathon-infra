import type { Violation } from '@/lib/types'

// Violation types from "Нарушения кассовой дисциплины по видео", section 3.
// D5 is left out: the catalog marks it "не флагать".
export const VIOLATION_TYPES = [
  ['A1', 'Пересчёт денег не на глазах у клиента'],
  ['A2', 'Приём денег без пересчёта и проверки подлинности'],
  ['A3', 'Выдача денег без пересчёта при клиенте'],
  ['A4', 'Кассир покинул рабочее место во время обслуживания'],
  ['A5', 'Сомнительную или поддельную купюру вернули клиенту'],
  ['B1', 'Лишние деньги открыто на столе, ящик или сейф открыт'],
  ['B2', 'Деньги ушли в личные вещи кассира'],
  ['B3', 'Личные вещи и личные деньги в кассе'],
  ['B4', 'Смартфон (устройство с камерой) в кассе'],
  ['B5', 'Сейф или хранилище открыто без присмотра, ключи оставлены'],
  ['B6', 'Деньги передали постороннему'],
  ['B7', 'Пересчёт или упаковка без контролирующего работника'],
  ['C1', 'Посторонний в кассе'],
  ['C2', 'Дверь кассы открыта во время работы'],
  ['C3', 'Деньги передали в обход окна или лотка'],
  ['D1', 'Сумку инкассации приняли без проверки'],
  ['D2', 'Повреждённую сумку вскрыли без инкассатора'],
  ['D3', 'Инкассация на виду у посторонних'],
  ['D4', 'Инкассатор зашёл в кассу'],
  ['E1', 'Камера закрыта или операция вне зоны камеры'],
] as const

const codeByType = new Map<string, string>(
  VIOLATION_TYPES.map(([code, type]) => [type.toLowerCase(), code])
)

// Prefer the code the backend sent; otherwise match the type against the catalog.
export function violationCode(violation: Violation) {
  return (
    violation.code || codeByType.get(violation.type.trim().toLowerCase()) || ''
  )
}
